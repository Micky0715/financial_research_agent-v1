def build_industry_chain(topic: str, sources: list[Source]) -> IndustryChain:
    template_key = next((k for k in _TEMPLATES if k in topic), None)
    rows = _TEMPLATES.get(template_key, _GENERIC)
    all_text = " ".join((s.title or "") + " " + (s.content or "")[:5000] for s in sources)

    nodes = []
    for layer, segment, desc, companies in rows:
        seg_terms = [t for t in segment.replace("/", " ").split() if t]
        verified = any(t in all_text for t in seg_terms)
        verified_companies = [c for c in companies if c in all_text]
        nodes.append(ChainNode(layer=layer, segment=segment, description=desc,
                               key_companies=verified_companies, verified_in_sources=verified))
    relations = [{"from": nodes[i].segment, "to": nodes[i + 1].segment, "relation": "供给/传导"}
                 for i in range(len(nodes) - 1)]

    chain = IndustryChain(
        industry=topic, nodes=nodes, relations=relations,
        price_transmission=_PRICE_NOTES.get(template_key or "", "上游成本向中下游传导，节奏取决于各环节议价能力"),
        tech_policy_nodes=["技术迭代与产业政策为关键外生变量，详见政策解读与来源正文"],
        data_basis="curated_template+source_verified" if template_key else "generic_template",
        limitation=("环节划分为内置行业常识模板（定性、不含数字）；关键公司仅保留在来源正文中"
                    "出现过的名单；" + ("无匹配模板，使用通用三段链" if not template_key else
                                       "环节 verified_in_sources=False 表示本次来源未覆盖该环节")),
    )
    return chain
